#!/usr/bin/env node
// Builds the medtech-market-data plugin from its single sources:
//   src/medtech-data.mjs  → skills/<each>/scripts/medtech-data.mjs (identical copies)
//   src/ground-rules.md   → the BEGIN/END ground-rules block in every SKILL.md
// Each skill carries its own copy of the CLI because claude.ai chat does not
// substitute ${CLAUDE_PLUGIN_ROOT}, so skills can't share one file at the root.
//
//   node build.mjs           sync copies + validate
//   node build.mjs --check   validate and fail if anything is out of sync (no writes)
//   node build.mjs --zip     sync, validate, then write dist/medtech-market-data.zip
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const ROOT = dirname(fileURLToPath(import.meta.url));
const NAME = 'medtech-market-data';
const BEGIN = '<!-- BEGIN ground-rules: generated by build.mjs from src/ground-rules.md, do not edit here -->';
const END = '<!-- END ground-rules -->';

function withRules(skillMd, rules) {
  const i = skillMd.indexOf(BEGIN), j = skillMd.indexOf(END);
  if (i < 0 || j < i) throw new Error('missing ground-rules markers');
  return skillMd.slice(0, i + BEGIN.length) + '\n' + rules.trim() + '\n' + skillMd.slice(j);
}

function frontmatter(md) {
  const m = md.match(/^---\n([\s\S]*?)\n---\n/);
  if (!m) return null;
  const get = k => { const r = m[1].match(new RegExp(`^${k}:\\s*(.*)$`, 'm')); return r ? r[1].trim() : null; };
  return { name: get('name'), description: get('description') };
}

// Returns { problems: [...], writes: [{path, content}] } without touching disk.
export function plan() {
  const problems = [], writes = [];
  const cli = readFileSync(join(ROOT, 'src/medtech-data.mjs'), 'utf8');
  const rules = readFileSync(join(ROOT, 'src/ground-rules.md'), 'utf8');
  const manifest = JSON.parse(readFileSync(join(ROOT, '.claude-plugin/plugin.json'), 'utf8'));
  if (manifest.name !== NAME) problems.push(`plugin.json name is "${manifest.name}", expected "${NAME}"`);
  const skills = readdirSync(join(ROOT, 'skills'), { withFileTypes: true }).filter(d => d.isDirectory()).map(d => d.name);
  if (!skills.length) problems.push('no skills found');
  for (const s of skills) {
    const dir = join(ROOT, 'skills', s);
    const mdPath = join(dir, 'SKILL.md');
    if (!existsSync(mdPath)) { problems.push(`${s}: no SKILL.md`); continue; }
    const md = readFileSync(mdPath, 'utf8');
    const fm = frontmatter(md);
    if (!fm || !fm.name || !fm.description) { problems.push(`${s}: SKILL.md frontmatter needs name and description`); continue; }
    if (fm.name !== s) problems.push(`${s}: frontmatter name "${fm.name}" must match its folder name`);
    if (!/^[a-z0-9-]{1,64}$/.test(fm.name)) problems.push(`${s}: name must be lowercase letters, digits, hyphens, ≤64 chars`);
    if (fm.description.length > 1024) problems.push(`${s}: description is ${fm.description.length} chars (max 1024)`);
    let want;
    try { want = withRules(md, rules); } catch (e) { problems.push(`${s}: ${e.message}`); continue; }
    if (want !== md) writes.push({ path: mdPath, content: want });
    const cliPath = join(dir, 'scripts', 'medtech-data.mjs');
    if (!existsSync(cliPath) || readFileSync(cliPath, 'utf8') !== cli) writes.push({ path: cliPath, content: cli });
  }
  return { problems, writes, skills };
}

function main() {
  const args = process.argv.slice(2);
  const { problems, writes, skills } = plan();
  if (problems.length) { console.error('✗ ' + problems.join('\n✗ ')); process.exit(1); }
  if (args.includes('--check')) {
    if (writes.length) {
      console.error('✗ out of sync — run `node plugins/medtech-market-data/build.mjs`:\n  ' + writes.map(w => w.path.slice(ROOT.length + 1)).join('\n  '));
      process.exit(1);
    }
    console.log(`✓ ${skills.length} skills in sync`);
    return;
  }
  for (const w of writes) { mkdirSync(dirname(w.path), { recursive: true }); writeFileSync(w.path, w.content); }
  console.log(`✓ ${skills.length} skills built (${writes.length} file(s) updated)`);
  if (args.includes('--zip')) {
    const dist = join(ROOT, 'dist');
    const out = join(dist, `${NAME}.zip`);
    mkdirSync(dist, { recursive: true });
    rmSync(out, { force: true });
    // Exactly one .claude-plugin/plugin.json at the archive's top level, plus
    // the skills and README; build inputs (src/, tests, this script) stay out.
    const r = spawnSync('zip', ['-qr', out, '.claude-plugin', 'skills', 'README.md', '-x', '*.DS_Store'], { cwd: ROOT, stdio: 'inherit' });
    if (r.error || r.status !== 0) { console.error('✗ zip failed (is the `zip` command installed?)'); process.exit(1); }
    console.log(`✓ ${out}`);
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
